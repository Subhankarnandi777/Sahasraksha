def physics_gates(df, station_cadence=None):
    g = pd.DataFrame(index=df.index)
    T, P, RH = df["T"].to_numpy(), df["P"].to_numpy(), df["RH"].to_numpy()

    # Cadence CANNOT be measured from timestamp gaps on a reindexed grid —
    # every station shows 1-hour gaps there regardless of true reporting
    # rate, once interpolation has filled the intermediate rows. It must be
    # supplied from outside, computed on non-interpolated data.
    if station_cadence is None:
        step_scale = np.ones(len(df))
    else:
        step_scale = df["station_id"].map(station_cadence).fillna(1.0).to_numpy()

    for ch, arr in zip(CHANNELS, [T, P, RH]):
        lo, hi = GROSS_LIMITS[ch]
        g[f"gate_range_{ch}"] = ((arr < lo) | (arr > hi)).astype(int)

    with np.errstate(invalid="ignore", divide="ignore"):
        Td = dewpoint_from_T_RH(T, np.clip(RH, 0.1, None))
    g["dewpoint"] = Td
    g["dewpoint_depression"] = T - Td
    g["gate_dewpoint"] = ((Td > T + 0.5) | (RH > 100.5)).astype(int)
    g["gate_t_record"]         = (T  > NATIONAL_T_MAX).astype(int)
    g["gate_dewpoint_ceiling"] = (Td > DEWPOINT_CEILING).astype(int)
    # ── Multivariate consistency: T, P and RH checked TOGETHER ──
    # (1) Hydrostatic: station P reduced to sea level with the station's own T and
    #     altitude must fall inside the physical band of Indian sea-level pressure.
    if "alt_m" in df.columns:
        with np.errstate(invalid="ignore", over="ignore"):
            P_msl = reduce_to_msl(P, T, df["alt_m"].to_numpy(dtype=float))
        g["P_msl"] = P_msl
        g["gate_msl_range"] = ((P_msl < MSL_RANGE[0]) | (P_msl > MSL_RANGE[1])).astype(int)
    # (2) Moisture budget: water content (specific humidity) needs Td AND P. RH may
    #     swing with temperature, but the air's actual water content cannot jump
    #     several g/kg between two reports unless a front passes.
    _alt = df["alt_m"].to_numpy(dtype=float) if "alt_m" in df.columns else np.zeros(len(df))
    P_eff = np.where(np.isfinite(P), P, 1013.25 * np.exp(-_alt / 8434.0))
    with np.errstate(invalid="ignore", over="ignore"):
        e_v = 6.112 * np.exp(17.67 * Td / (Td + 243.5))
        q = 622.0 * e_v / (P_eff - 0.378 * e_v)                    # g/kg
    g["q_gkg"] = q
    dq = pd.Series(q, index=df.index).groupby(df["station_id"]).diff().abs().to_numpy()
    g["d_q"] = np.nan_to_num(dq)
    g["gate_moisture_jump"] = (np.nan_to_num(dq) > Q_JUMP_MAX * np.sqrt(step_scale)).astype(int)
    # (3) Data integrity: each record must arrive once, in time order.
    if "ingest_bad" in df.columns:                      # verdict from ingest_integrity()
        g["gate_timestamp"] = df["ingest_bad"].to_numpy().astype(int)
    elif "timestamp" in df.columns:
        _ts = pd.to_datetime(df["timestamp"])
        _dt = _ts.groupby(df["station_id"]).diff()
        g["gate_timestamp"] = (_dt <= pd.Timedelta(0)).fillna(False).astype(int).to_numpy()

    for ch in CHANNELS:
        d = df.groupby("station_id", observed=True)[ch].diff().abs().to_numpy()
        g[f"d_{ch}"] = np.nan_to_num(d)
        g[f"gate_step_{ch}"] = (np.nan_to_num(d) > STEP_LIMITS[ch]*np.sqrt(step_scale)).astype(int)

    hourly_only = (step_scale <= 1.0)
    for ch in CHANNELS:
        g[f"runlen_{ch}"] = _run_length(df, ch)
        run_hours = g[f"runlen_{ch}"] * step_scale
        # Frozen-run detection empirically has zero precision at every
        # threshold >=12h, for ALL THREE channels, on 3-hourly ISD stations
        # (341,668 obs tested; T, RH and P swept independently, same result
        # each time). The signature is valid for hourly-cadence reporting
        # only (e.g. AWS_HYD) and is disabled at coarser cadence.
        g[f"gate_frozen_{ch}"] = ((run_hours >= FROZEN_MIN_RUN[ch]) & hourly_only).astype(int)

    # A channel counts as 'missing' only if this station normally reports it.
    # A station with no barometer (e.g. AWS_BLR, AWS_SHL) is not failing every hour.
    _avail = df[CHANNELS].notna().groupby(df["station_id"]).transform("mean")
    g["gate_missing"] = (df[CHANNELS].isna() & (_avail >= 0.5)).any(axis=1).astype(int)

    gate_cols = [c for c in g.columns
                 if c.startswith("gate_") and c != "gate_missing"]
    g["physics_flag"] = (g[gate_cols].sum(axis=1) > 0).astype(int)
    return g


