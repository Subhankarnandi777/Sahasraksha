def ingest_integrity(df):
    """Check ARRIVAL order before anything re-sorts it: a record whose timestamp is
    not later than every earlier record of its station is a duplicate or arrived
    out of order. Then give the time-series layers a clean, time-ordered copy,
    carrying the verdict along as `ingest_bad`."""
    ts = pd.to_datetime(df["timestamp"])
    prev_max = ts.groupby(df["station_id"]).cummax().groupby(df["station_id"]).shift()
    bad = (ts <= prev_max).fillna(False).to_numpy()
    return (df.assign(ingest_bad=bad.astype(int))
              .sort_values(["station_id", "timestamp"], kind="stable").reset_index(drop=True))


