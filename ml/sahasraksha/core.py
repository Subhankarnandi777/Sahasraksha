def operator_label(F, mechanism):
    """What an operator sees. A physically impossible VALUE is named as such;
    otherwise the MECHANISM. Root-cause precision is scored on `mechanism` only."""
    cols = [g for g in STRONG_IMPOSSIBLE if g in F.columns]
    imp = F[cols].to_numpy().max(axis=1) == 1 if cols else np.zeros(len(F), bool)
    lab = np.where(imp, "impossible", np.asarray(mechanism, dtype=object))
    ts_bad = (F["gate_timestamp"].to_numpy() == 1) if "gate_timestamp" in F.columns else np.zeros(len(F), bool)
    return np.where(ts_bad & ~imp, "corrupt", lab)


