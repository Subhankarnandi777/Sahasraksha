def calculate_severity(df, F, flag, rc_labels=None):
    """
    Severity = physical impact SO FAR: the largest deviation from the station's
    expected value (normalised per channel) x sqrt(hours the episode has lasted
    up to this row). Computed causally row by row, so a live stream gets the
    same number. Grades are relative to the current alert queue -- worst 20% =
    CRITICAL, next 30% = MAJOR, rest = MINOR -- so they always rank the queue
    instead of saturating.
    """
    IMPACT_SCALE = {"T": 15.0, "P": 10.0, "RH": 50.0}
    repaired_df = impute(df, F, flag)
    norm_dev = np.zeros(len(df))
    for ch in ["T", "P", "RH"]:
        d = np.abs(df[ch].to_numpy(float) - repaired_df[f"{ch}_repaired"].to_numpy(float)) / IMPACT_SCALE[ch]
        norm_dev = np.fmax(norm_dev, np.nan_to_num(d))

    is_f = np.asarray(flag) == 1
    sid = df["station_id"].to_numpy()
    new_ep = (is_f != np.r_[False, is_f[:-1]]) | (sid != np.r_[sid[:1], sid[:-1]])
    ep = np.cumsum(new_ep)

    severities = np.zeros(len(df))
    if is_f.any():
        s_ = pd.Series(norm_dev[is_f]); g_ = ep[is_f]
        dur = s_.groupby(g_).cumcount().to_numpy() + 1          # hours so far
        run = s_.groupby(g_).cummax().to_numpy()                 # worst deviation so far
        severities[is_f] = np.round(1.0 - np.exp(-run * np.sqrt(dur)), 3)

    grades = np.array(["OK"] * len(df), dtype=object)
    if is_f.any():
        q50, q80 = np.quantile(severities[is_f], [0.50, 0.80])
        grades[is_f] = np.where(severities[is_f] >= q80, "CRITICAL",
                        np.where(severities[is_f] >= q50, "MAJOR", "MINOR"))
    return severities, grades


