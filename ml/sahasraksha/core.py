def _regional_agreement(res, df, nbrs, z_min=2.0, ratio=0.5):
    """For every row: do at least REGIONAL_MIN_NEIGHBOURS neighbours (within 700 km)
    show the SAME departure at the SAME time -- same sign, at least half the size,
    on the channel where this station departs most? A depression, a heat wave or a
    cold wave moves a whole region together; a failing sensor moves alone."""
    sid = df["station_id"].to_numpy(); ts = pd.to_datetime(df["timestamp"]).to_numpy()
    key = pd.MultiIndex.from_arrays([ts, sid])
    agree, zabs = [], []
    for ch in CHANNELS:
        z = res[f"z_{ch}"].to_numpy()
        wide = (pd.DataFrame({"ts": ts, "sid": sid, "z": z})
                  .groupby(["ts", "sid"])["z"].first().unstack())
        W = wide.to_numpy(); cols = list(wide.columns); pos = {c: i for i, c in enumerate(cols)}
        A = np.zeros_like(W)
        with np.errstate(invalid="ignore"):
            for c in cols:
                nb = [pos[n] for n in nbrs.get(c, []) if n in pos]
                if not nb:
                    continue
                zs = W[:, [pos[c]]]; zn = W[:, nb]
                ok = (np.sign(zn) == np.sign(zs)) & (np.abs(zn) >= ratio * np.abs(zs)) & (np.abs(zs) >= z_min)
                A[:, pos[c]] = ok.sum(axis=1)
        agree.append(pd.DataFrame(A, index=wide.index, columns=cols).stack().reindex(key).to_numpy())
        zabs.append(np.abs(np.nan_to_num(z)))
    dom = np.argmax(np.vstack(zabs), axis=0)                      # channel this station departs most on
    n_agree = np.nan_to_num(np.vstack(agree))[dom, np.arange(len(df))]
    return (n_agree >= REGIONAL_MIN_NEIGHBOURS).astype(int)


